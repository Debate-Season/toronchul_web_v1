/** province code → District[] */
export const DISTRICTS_BY_PROVINCE: Record<string, readonly District[]> =
  Object.fromEntries(
    Object.entries(RAW_DISTRICTS).map(([provinceCode, list]) => [
      provinceCode,
      list.map(([code, name]) => ({ code, name, provinceCode })),
    ]),
  );

const PROVINCE_INDEX: Record<string, Province> = Object.fromEntries(
  PROVINCES.map((p) => [p.code, p]),
);

// 모바일 _all 에는 제주가 빠져 있었으나(버그) 여기서는 전부 포함.
const DISTRICT_INDEX: Record<string, District> = Object.fromEntries(
  Object.values(DISTRICTS_BY_PROVINCE)
    .flat()
    .map((d) => [d.code, d]),
);

export function getDistricts(provinceCode: string): readonly District[] {
  return DISTRICTS_BY_PROVINCE[provinceCode] ?? [];
}

/** code 로 province 조회. 없으면 서울 fallback (모바일 fromCode 동작 미러). */
export function provinceFromCode(code: string): Province {
  return PROVINCE_INDEX[code] ?? PROVINCES[0];
}

/** code 로 district 조회. 없으면 null. */
export function districtFromCode(code: string): District | null {
  return DISTRICT_INDEX[code] ?? null;
}
